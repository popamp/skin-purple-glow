"""Builds Purple Glow: the SVG sheets, the bar's and the library's pictures and skin.toml.

    python3 -I -B tools/gen.py [skin folder]

Every window is put together from the same parts (tools/parts.py): one
panel and edge, one title strip with one set of title buttons, where only
the window's name differs, one kind of button, well and thumb. text.svg and
numbers.svg (in fonts/) are the skin's lettering and are drawn by hand; the rest is
written here. Running it again gives the same files.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import art_bar  # noqa: E402
import art_eq  # noqa: E402
import art_main  # noqa: E402
import art_pl  # noqa: E402
import windows  # noqa: E402
from kit import Picture, colour_sets, sheet_file  # noqa: E402

# sheet: (width, height, drawing); text.svg and numbers.svg are the lettering, drawn by hand
SHEETS = {
    "main": (275, 116, art_main.main),
    "cbuttons": (136, 36, art_main.cbuttons),
    "titlebar": (344, 87, art_main.titlebar),
    "shufrep": (92, 85, art_main.shufrep),
    "volume": (68, 433, art_main.volume),
    "balance": (68, 433, art_main.balance),
    "monoster": (58, 24, art_main.monoster),
    "playpaus": (42, 9, art_main.playpaus),
    "posbar": (307, 10, art_main.posbar),
    "eqmain": (275, 315, art_eq.eqmain),
    "eq_ex": (275, 82, art_eq.eq_ex),
    "pledit": (280, 186, art_pl.pledit),
}
LETTERING = ("text", "numbers")

META = """\
# Purple Glow. Generated by tools/gen.py; change the script, not this file.

[meta]
name = "Purple Glow"
author = "Popamp, after the Winamp skin Purple Glow v2"
format_version = 1
min_popamp = "1.0.0"
"""

PLAYLIST = {"normal": "ink", "current": "glow-light", "normal_bg": "#000000", "selected_bg": "glow-dim"}

# Background, background dots, 16 spectrum colours from the top of a bar down, 5 oscilloscope colours, the peak dots.
VIS = ["#000000", "glow-deep", *["glow-light"] * 4, *["glow"] * 6, *["glow-mid"] * 6,
       "glow-light", "glow", "glow", "glow-mid", "glow-dim", "glow-light"]  # fmt: skip


def skin_toml():
    lines = [META, *colour_sets(), "", "[sheets]"]
    lines += [f'{name} = "{sheet_file(name)}"' for name in (*SHEETS, *LETTERING)]
    lines += ["", "[playlist]", *(f'{k} = "{c}"' for k, c in PLAYLIST.items())]
    lines += ["", "[vis]", "colors = ["]
    lines += ["    " + ", ".join(f'"{c}"' for c in VIS[i : i + 8]) + "," for i in range(0, 24, 8)]
    lines += ["]", *windows.bar_window(), *windows.library_window()]
    return "\n".join(lines) + "\n"


def draw(path, w, h, art):
    p = Picture(w, h)
    art(p)
    p.save(path)


def build(out):
    for name, (w, h, art) in SHEETS.items():
        draw(os.path.join(out, sheet_file(name)), w, h, art)
    for name, (w, h, art) in art_bar.PICTURES.items():
        draw(os.path.join(out, "bar", f"{name}.svg"), w, h, art)
    draw(os.path.join(out, "ml", "title.svg"), art_pl.PLATE_W, 41, art_pl.ml_title)
    with open(os.path.join(out, "skin.toml"), "w", encoding="utf-8") as f:
        f.write(skin_toml())


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
